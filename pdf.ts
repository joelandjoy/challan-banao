import { jsPDF } from 'jspdf';
import { autoTable } from 'jspdf-autotable';
import type { BillingDocument, ShopProfile } from '../types';
import { displayDate, money } from './format';

export function downloadDocumentPdf(document: BillingDocument, profile?: ShopProfile | null) {
  const pdf = new jsPDF({ orientation: 'portrait', unit: 'mm', format: 'a4' });
  const shop = document.shop_snapshot || {
    shop_name: profile?.shop_name || 'Shop', owner_name: profile?.owner_name || '',
    address: profile?.address || null, phone: profile?.phone || null, logo_url: profile?.logo_url || null,
  };
  const isBill = document.document_type === 'bill';
  const pageWidth = pdf.internal.pageSize.getWidth();
  pdf.setFont('helvetica', 'bold');
  pdf.setFontSize(20);
  pdf.text(shop.shop_name || 'Shop', 14, 19, { maxWidth: pageWidth - 28 });
  pdf.setFont('helvetica', 'normal');
  pdf.setFontSize(9);
  let y = 25;
  if (shop.owner_name) { pdf.text(`Owner: ${shop.owner_name}`, 14, y); y += 5; }
  if (shop.address) { const lines = pdf.splitTextToSize(shop.address, 105); pdf.text(lines, 14, y); y += lines.length * 4; }
  if (shop.phone) { pdf.text(`Phone: ${shop.phone}`, 14, y); y += 5; }
  pdf.setDrawColor(210, 210, 210); pdf.line(14, y + 2, pageWidth - 14, y + 2);

  const rightX = pageWidth - 14;
  pdf.setFont('helvetica', 'bold'); pdf.setFontSize(15);
  pdf.text(isBill ? 'BILL / INVOICE' : 'DELIVERY CHALLAN', rightX, 19, { align: 'right' });
  pdf.setFontSize(10); pdf.setFont('helvetica', 'normal');
  pdf.text(document.document_number, rightX, 26, { align: 'right' });
  pdf.text(`Date: ${displayDate(document.issue_date)}`, rightX, 32, { align: 'right' });

  let customerY = y + 10;
  if (document.customer_snapshot) {
    pdf.setFont('helvetica', 'bold'); pdf.text('Bill to', 14, customerY);
    pdf.setFont('helvetica', 'normal'); customerY += 5;
    pdf.text(document.customer_snapshot.name, 14, customerY); customerY += 4.5;
    if (document.customer_snapshot.phone) { pdf.text(`Phone: ${document.customer_snapshot.phone}`, 14, customerY); customerY += 4.5; }
    if (document.customer_snapshot.address) {
      const addressLines = pdf.splitTextToSize(document.customer_snapshot.address, 100);
      pdf.text(addressLines, 14, customerY); customerY += addressLines.length * 4;
    }
  }
  const items = document.items || [];
  autoTable(pdf, {
    startY: Math.max(customerY + 4, y + 14),
    head: [['#', 'Item description', 'Qty', 'Rate', 'Amount']],
    body: items.map((item, index) => [
      String(index + 1), `${item.name_snapshot}${item.sku_snapshot ? `\nSKU: ${item.sku_snapshot}` : ''}`,
      `${item.quantity}${item.unit_snapshot ? ` ${item.unit_snapshot}` : ''}`,
      money(item.rate), money(item.line_total ?? item.quantity * item.rate),
    ]),
    theme: 'grid',
    styles: { font: 'helvetica', fontSize: 9, cellPadding: 3, textColor: [25, 25, 25], lineColor: [220, 220, 220], lineWidth: 0.2, overflow: 'linebreak' },
    headStyles: { fillColor: [245, 245, 245], textColor: [25, 25, 25], fontStyle: 'bold' },
    columnStyles: { 0: { cellWidth: 10 }, 1: { cellWidth: 'auto' }, 2: { cellWidth: 23, halign: 'right' }, 3: { cellWidth: 30, halign: 'right' }, 4: { cellWidth: 32, halign: 'right' } },
    margin: { left: 14, right: 14 },
  });
  let totalsY = ((pdf as jsPDF & { lastAutoTable?: { finalY: number } }).lastAutoTable?.finalY ?? customerY) + 9;
  const totalRows: Array<[string, string]> = [['Subtotal', money(document.subtotal)]];
  if (document.discount_amount > 0) totalRows.push(['Discount', `− ${money(document.discount_amount)}`]);
  if (document.tax_rate > 0) totalRows.push([`Tax (${document.tax_rate}%)`, money(document.tax_amount)]);
  totalRows.push(['Total', money(document.total)]);
  for (const [label, value] of totalRows) {
    if (totalsY > 265) { pdf.addPage(); totalsY = 20; }
    const isTotal = label === 'Total';
    pdf.setFont('helvetica', isTotal ? 'bold' : 'normal');
    pdf.setFontSize(isTotal ? 12 : 10);
    pdf.text(label, pageWidth - 80, totalsY);
    pdf.text(value, pageWidth - 14, totalsY, { align: 'right' });
    totalsY += isTotal ? 8 : 6;
  }
  if (document.notes) {
    if (totalsY > 265) { pdf.addPage(); totalsY = 20; }
    pdf.setFont('helvetica', 'bold'); pdf.setFontSize(9); pdf.text('Notes', 14, totalsY + 2);
    pdf.setFont('helvetica', 'normal');
    pdf.text(pdf.splitTextToSize(document.notes, pageWidth - 28), 14, totalsY + 7);
  }
  const pageCount = pdf.getNumberOfPages();
  for (let page = 1; page <= pageCount; page++) {
    pdf.setPage(page); pdf.setFontSize(8); pdf.setTextColor(120);
    pdf.text(`Generated by Ledger · Page ${page} of ${pageCount}`, pageWidth / 2, 289, { align: 'center' });
  }
  pdf.save(`${document.document_number || (isBill ? 'Bill' : 'Challan')}.pdf`);
}
